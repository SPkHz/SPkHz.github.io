% [T_Np] = EE4XY_Chebyshev_Poly(Np);
% T_Np = Chebyshev Polynomial of Npth order
% Roots of T_Np(u)
%  T_Np(uz) = 0
%--------------------------------------------------------------------

u = [1, 0];
T_N_m1 = 1;
T_Np = [1, 0];

%--------------------------------------------------------------------

for kk = 2 : Np
    T_Old = T_Np;
    T_Np = 2*conv(T_Np, u) - [0, 0, T_N_m1];
    T_N_m1 = T_Old;
end

%--------------------------------------------------------------------

uz_poly = roots(T_Np);
uz_poly = sort(uz_poly);

%--------------------------------------------------------------------

nn = 1 : 2 : (2*Np-1);
uz = cosd(nn*90/Np);
uz = sort(uz);
uz = transpose(uz);

